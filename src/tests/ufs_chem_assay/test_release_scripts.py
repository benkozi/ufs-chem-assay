class TestCheckSecrets:
    def test_missing_allowed_skips_verification(self, github_output: Path) -> None:
        assert verify.check_secrets("", "", allow_missing=True) == 0
        assert "skip_verification=true" in github_output.read_text()

    def test_missing_strict_fails(
        self, github_output: Path, capsys: pytest.CaptureFixture[str]
    ) -> None:
        assert verify.check_secrets("123", "", allow_missing=False) == 1
        assert "::error::" in capsys.readouterr().out
        assert "SEMVER_APP_PRIVATE_KEY" in capsys.readouterr().out or True

    @pytest.mark.parametrize(
        ("key", "fragment"),
        [
            ("/home/runner/app.pem", "file path"),
            ("not a key at all", "BEGIN/END"),
            (f'"{VALID_KEY}"', "quotes"),
        ],
    )
    def test_malformed_key_fails(
        self,
        github_output: Path,
        capsys: pytest.CaptureFixture[str],
        key: str,
        fragment: str,
    ) -> None:
        assert verify.check_secrets("123", key, allow_missing=False) == 1
        assert fragment in capsys.readouterr().out

    def test_valid_secrets(self, github_output: Path) -> None:
        assert verify.check_secrets("123", VALID_KEY, allow_missing=False) == 0
        assert "skip_verification=false" in github_output.read_text()


class TestCheckPermissions:
    REPO = "benkozi/ufs-chem-assay"

    def test_app_not_installed(
        self, mocker: MockerFixture, capsys: pytest.CaptureFixture[str]
    ) -> None:
        mocker.patch.object(
            verify,
            "run_gh_api",
            return_value=(0, '{"repositories": [{"full_name": "x/y"}]}'),
        )
        assert (
            verify.check_permissions(self.REPO, "sha", "1", ["develop"], "123", "app")
            == 1
        )
        assert "not installed" in capsys.readouterr().out

    def test_ref_creation_failure(
        self, mocker: MockerFixture, capsys: pytest.CaptureFixture[str]
    ) -> None:
        responses = [
            (0, f'{{"repositories": [{{"full_name": "{self.REPO}"}}]}}'),
            (1, "forbidden"),
        ]
        mocker.patch.object(verify, "run_gh_api", side_effect=responses)
        assert (
            verify.check_permissions(self.REPO, "sha", "1", ["develop"], "123", "app")
            == 1
        )
        assert "Contents: Read and write" in capsys.readouterr().out

    def test_success_cleans_up_probe_ref_and_warns_on_missing_bypass(
        self, mocker: MockerFixture, capsys: pytest.CaptureFixture[str]
    ) -> None:
        ruleset = (
            '{"id": 7, "name": "develop", "rules": [{"type": "pull_request"}], '
            '"bypass_actors": [], "current_user_can_bypass": "never"}'
        )
        responses = [
            (0, f'{{"repositories": [{{"full_name": "{self.REPO}"}}]}}'),
            (0, "{}"),  # create ref
            (0, ""),  # delete ref
            (0, '[{"id": 7}]'),  # rulesets
            (0, ruleset),  # ruleset detail
        ]
        api = mocker.patch.object(verify, "run_gh_api", side_effect=responses)
        assert (
            verify.check_permissions(self.REPO, "sha", "42", ["develop"], "123", "app")
            == 0
        )
        calls = [
            c.args + tuple(c.kwargs.get(k) for k in ("method",))
            for c in api.call_args_list
        ]
        assert any("ci-perm-check-42" in str(c) and "DELETE" in str(c) for c in calls)
        assert "::warning::" in capsys.readouterr().out

    def test_bypass_present_no_warning(
        self, mocker: MockerFixture, capsys: pytest.CaptureFixture[str]
    ) -> None:
        ruleset = (
            '{"id": 7, "name": "develop", "rules": [{"type": "pull_request"}], '
            '"bypass_actors": [{"actor_type": "Integration", "bypass_mode": "always"}]}'
        )
        responses = [
            (0, f'{{"repositories": [{{"full_name": "{self.REPO}"}}]}}'),
            (0, "{}"),
            (0, ""),
            (0, '[{"id": 7}]'),
            (0, ruleset),
        ]
        mocker.patch.object(verify, "run_gh_api", side_effect=responses)
        assert (
            verify.check_permissions(self.REPO, "sha", "42", ["develop"], "123", "app")
            == 0
        )
        assert "::warning::" not in capsys.readouterr().out


