class TestReportHelpers:
    def test_is_prerelease(self) -> None:
        assert report_release.is_prerelease("0.2.0-rc.1", "main")
        assert report_release.is_prerelease("0.2.0", "develop")
        assert not report_release.is_prerelease("0.2.0", "main")

    def test_extract_version_from_toml(self) -> None:
        assert (
            report_release.extract_version_from_toml(
                '[project]\nname = "x"\nversion = "v0.1.0"\n'
            )
            == "0.1.0"
        )
        assert report_release.extract_version_from_toml("[project]\n") == ""

    def test_describe_actions_release(self) -> None:
        lines = report_release.describe_actions(
            "Squash Merge", True, "0.2.0-rc.1", "v0.2.0-rc.1", True
        )
        text = "\n".join(lines)
        assert "Squash Merge" in lines[0]
        assert "`v0.2.0-rc.1`" in text
        assert "CHANGELOG.md" in text and "uv.lock" in text and "pyproject.toml" in text
        assert "prerelease" in text
        assert "ontainer" not in text

    def test_describe_actions_no_release(self) -> None:
        lines = report_release.describe_actions("", False, "", "", False)
        assert "No release" in "\n".join(lines)


class TestGenerateReport:
    def test_dual_strategy_table(self) -> None:
        report = report_release.generate_report(
            target="develop",
            current_version="0.1.0-rc.1",
            dry_run=True,
            version_merge="0.2.0-rc.1",
            tag_merge="v0.2.0-rc.1",
            released_merge=True,
            version_squash="0.2.0-rc.1",
            tag_squash="v0.2.0-rc.1",
            released_squash=True,
            diff_merge="--- a\n+++ b",
            diff_squash="--- c\n+++ d",
        )
